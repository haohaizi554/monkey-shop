function initialLocale(): 'en' | 'zh' {
  if (typeof localStorage === 'undefined') {
    return 'zh'
  }
  const saved = localStorage.getItem('monkeyshop-locale')
  return supportedLocales.has(saved ?? '') ? (saved as 'en' | 'zh') : 'zh'
}

